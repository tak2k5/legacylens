def _esc(text: str | None) -> str:
    return (text or "").replace("|", "\\|").replace("\n", " ")


def render(
    index: Index,
    program: str,
    rules: RuleSet | None = None,
    checks: list[dict] | None = None,
    lang: str = "vi",
    link_base: str = "",
) -> str:
    L = LABELS[lang]
    p = index.program(program)
    rel = Path(p.path).resolve().relative_to(index.root.resolve()).as_posix()
    link = f"{link_base}{rel}"
    out = [f"# {L['title']}: {p.program_id}", "", f"_{L['generated']}_", "", f"## {L['overview']}", ""]
    out += [
        f"| {L['kind']} | {L[p.kind]} |",
        "| --- | --- |",
        f"| {L['loc']} | {p.loc} |",
        f"| {L['source']} | [{rel}]({link}) |",
    ]
    if rules:
        out += ["", f"**{L['purpose']}.** {rules.purpose}"]

    seen = set()
    io_rows = []
    for op in p.file_ops:
        ds = index.dataset_for(p, op.file)
        if (ds, op.mode) in seen:
            continue
        seen.add((ds, op.mode))
        name = op.file if ds == op.file else f"{op.file} → `{ds}`"
        io_rows.append(f"| {name} | {L[op.mode]} | [{op.line}]({link}#L{op.line}) |")
    if io_rows:
        out += [
            "",
            f"## {L['files']}",
            "",
            f"| {L['file']} | {L['mode']} | {L['line']} |",
            "| --- | --- | --- |",
            *io_rows,
        ]

    transfers = p.transfers()
    if transfers:
        out += ["", f"## {L['transfers']}", "", f"| {L['target']} | {L['verb']} | {L['line']} |", "| --- | --- | --- |"]
        out += [f"| {t} | {v} | [{line}]({link}#L{line}) |" for v, t, line in transfers]

    callers = [c for c in index.callers(p.program_id) if c["from"].startswith("program:")]
    jobs = [c for c in index.callers(p.program_id) if c["from"].startswith("job:")]
    if callers:
        out += ["", f"## {L['callers']}", "", ", ".join(sorted({c["from"].split(":", 1)[1] for c in callers}))]
    if jobs:
        out += ["", f"## {L['jobs']}", "", ", ".join(sorted({c["from"].split(":", 1)[1] for c in jobs}))]
    if p.copybooks:
        out += ["", f"## {L['copybooks']}", "", ", ".join(f"`{c.name}`" for c in p.copybooks)]

    edges = sorted({(para.name, r.name) for para in p.paragraphs for r in para.performs})
    if edges:
        ids = {name: f"p{i}" for i, name in enumerate(sorted({n for e in edges for n in e}))}
        out += ["", f"## {L['flow']}", "", "```mermaid", "flowchart TD"]
        out += [f'    {ids[a]}["{a}"] --> {ids[b]}["{b}"]' for a, b in edges[:80]]
        out += ["```"]

    out += ["", f"## {L['rules']}", ""]
    if not rules:
        out.append(L["none"])
    else:
        by_id = {c.get("rule"): c for c in checks or []}
        out += [
            f"| {L['id']} | {L['summary']} | {L['condition']} | {L['outcome']} | {L['cite']} | {L['check']} |",
            "| --- | --- | --- | --- | --- | --- |",
        ]
        for r in rules.rules:
            cites = ", ".join(
                f"[{c.start_line}-{c.end_line}]({link}#L{c.start_line}-L{c.end_line})"
                if c.program == p.program_id
                else f"{c.program}:{c.start_line}-{c.end_line}"
                for c in r.citations
            )
            chk = by_id.get(r.id)
            mark = (
                "" if chk is None else (L["ok"] if chk["valid"] else f"{L['bad']}: {_esc('; '.join(chk['problems']))}")
            )
            out.append(f"| {r.id} | {_esc(r.summary)} | {_esc(r.condition)} | {_esc(r.outcome)} | {cites} | {mark} |")
    return "\n".join(out) + "\n"
